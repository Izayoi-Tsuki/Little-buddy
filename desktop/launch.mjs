import { spawn } from 'node:child_process';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const require = createRequire(import.meta.url);
const root = dirname(dirname(fileURLToPath(import.meta.url)));
const env = { ...process.env };
delete env.ELECTRON_RUN_AS_NODE;
const args = process.argv.slice(2);
const child = spawn(require('electron'), [join(root, 'desktop/buddy-main.mjs'), ...args.filter(arg => arg !== '--files')], { cwd: root, env, stdio: 'inherit', windowsHide: false });
child.on('error', error => { console.error(`桌面应用启动失败：${error.message}`); process.exitCode = 1; });
child.on('exit', code => { process.exitCode = code ?? 1; });
